package main

import (
	"fmt"
	"math"
)

func main() {
	fmt.Println(math.Ceil(1.4))   //dibulatkan keatas
	fmt.Println(math.Floor(1.4))  // dibulatkan kebawah
	fmt.Println(math.Round(1.4))  // dibulatkan yang terdekat
	fmt.Println(math.Max(10, 11)) // dibulatkan maximal
	fmt.Println(math.Min(10, 11)) // dibulatkan minimal

}
